    P("### `@register_hook(\"name\")` — Request/response hook")
    P("")
    P("Five hook points to intercept and modify requests or responses.")
    P("")
    P("```python")
    P("# specs/plugins/my_hooks.py")
    P("from cliyard.plugin import register_hook")
    P("from cliyard.engine.assembler import Request")
    P("")
    P('@register_hook("add_timestamp")')
    P("def add_timestamp(req: Request) -> Request:")
    P('    """Add query timestamp to every outgoing request."""')
    P('    import time')
    P('    req.query_params.setdefault("_t", str(int(time.time() * 1000)))')
    P("    return req")
    P("")
    P('@register_hook("keta_upload")')
    P("def keta_upload(req: Request) -> Request:")
    P('    """Add KetaDB resumable upload fields for file uploads."""')
    P("    if not req.files:")
    P("        return req")
    P("    file_path = None")
    P("    for val in req.files.values():")
    P("        fobj = val[1] if isinstance(val, tuple) and len(val) >= 2 else val")
    P("        if hasattr(fobj, \"name\"):")
    P("            file_path = fobj.name")
    P("            break")
    P("    if not file_path:")
    P("        return req")
    P("    import hashlib, os, time")
    P("    file_size = os.path.getsize(file_path)")
    P("    file_md5 = hashlib.md5(open(file_path, \"rb\").read()).hexdigest()")
    P('    req.query_params.update({')
    P('        "resumableChunkNumber": "1",')
    P('        "resumableTotalChunks": "1",')
    P('        "resumableTotalSize": str(file_size),')
    P('        "resumableIdentifier": file_md5,')
    P('        "resumableFilename": os.path.basename(file_path),')
    P("    })")
    P("    return req")
    P("")
    P('@register_hook("import_result_message")')
