    P('      - if: \'{{ step.check_repo.repos | selectattr("name", "equalto", flow.name) | list | length > 0 }}\'')
    P("        then:")
    P("          - type: echo")
    P('            message: "Repo {{ flow.name }} already exists"')
    P("          - action: return")
    P("      - else:")
    P("          steps:")
    P("            - id: do_create")
    P("              description: Create repository")
    P("              use: repo.create")
    P("              params:")
    P("                name: '{{ flow.name }}'")
    P("                repo_type: '{{ flow.type }}'")
    P("")
    P("  # Step 3: verify")
    P("  - id: verify")
    P("    description: Verify creation")
    P("    use: repo.list")
    P("    params:")
    P("      pageSize: 100")
    P("    on_result:")
    P('      - if: \'{{ step.verify.repos | selectattr("name", "equalto", flow.name) | list | length > 0 }}\'')
    P("        then:")
    P("          - type: echo")
    P('            message: "✓ Repo {{ flow.name }} created"')
    P("```")
    P("")

    P("### Step types")
    P("")
    P("| Form | Description |")
    P("|------|-------------|")
    P("| `use: resource.method` | Invoke an existing CLI command |")
    P("| `type: plugin:xxx` | Execute a registered plugin step |")
    P("| `type: echo` | Print a message to console |")
    P("| `action: return/abort/warn/skip` | Control flow within on_result |")
    P("| `include: _flow_file.yaml` | Include steps from another file |")
    P("")

    P("### Template references")
    P("")
    P("| Reference | Scope |")
    P("|-----------|-------|")
    P("| `{{ flow.xxx }}` | CLI parameter value |")
