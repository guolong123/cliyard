    P("### Loops")
    P("")
    P("```yaml")
    P("# for_each — iterate over a list")
    P("- id: batch")
    P("  for_each:")
    P("    items: '{{ step.list.items }}'")
    P("    as: item")
    P("    steps:")
    P("      - id: process")
    P("        use: resource.method")
    P("        params:")
    P("          body:")
    P("            name: '{{ item.name }}'")
    P("")
