@click.command()
@click.option(
    "-o",
    "--output",
    default=None,
    type=str,
    help="Output file path (default: stdout)",
)
def usage(output: str | None) -> None:
    """Generate AGENTS.md for the current project.

    Outputs a static reference covering cliyard's subcommands, YAML spec
    conventions, plugin system, and flow orchestration.  No spec directory
    needed — works from any directory.
    """
    docs = generate()

    if output:
        out_path = Path(output)
        out_path.write_text(docs, encoding="utf-8")
        click.echo(f"Written to {out_path}", err=True)
    else:
        click.echo(docs)
