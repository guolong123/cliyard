    P("- id: deploy")
    P("  use: resource.method")
    P("  retry:")
    P("    max_attempts: 3")
    P("    delay: 2")
    P("    backoff: 2       # delays: 2s → 4s → 8s")
    P("    on_exhausted:")
    P("      action: abort")
    P('      message: "Deploy failed after 3 attempts"')
    P("")
